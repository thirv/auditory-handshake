"""Typed config loader for the ``configs/`` YAML tree (PLAN.md §5, §12).

Layout (repo root)::

    configs/
      defaults.yaml            # seed, sample_rate_hz, audio bands
      rooms/<name>.yaml        # one preset per room (cabin, small_office, ...)
      phy_constraints.yaml     # M2 output placeholder (regenerated by sims/02)

This module is the **single place** configs are read from disk. Simulation
code imports :func:`load_defaults` / :func:`list_room_presets` /
:func:`load_room_preset` and never touches ``yaml`` or ``pathlib`` for these
paths. The presets are validated into a frozen :class:`RoomPreset` so that a
typo in the YAML fails loudly at load time, not inside the acoustic engine.
The S17.2 C2 frontier-sweep grid lives in :class:`FrontierConfig` (
:func:`load_frontier`), loaded from ``configs/c2_frontier.yaml``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

import yaml

#: Repo-root-relative path of the ``configs/`` tree.
CONFIGS_DIR = Path("configs")
ROOMS_SUBDIR = "rooms"

_REQUIRED_FACES = ("x", "y", "z")
_BUNDLED_NAMES = (
    "cabin",
    "conference_room",
    "corridor",
    "small_hall",
    "small_office",
)

DEVICES_SUBDIR = "devices"
SCENARIOS_SUBDIR = "scenarios"

#: Allowed ``kind`` values for a device preset (TX/RX transducer).
_DEVICE_KINDS = ("loudspeaker", "microphone", "speaker", "phone")

#: Allowed ``frame_mode`` values for a scenario (PLAN §2.4).
_FRAME_MODES = ("shout", "one_half_way", "two_way", "three_way")

#: Device and scenario presets expected to ship with the repo (S2.6 / S2.7).
_BUNDLED_DEVICE_NAMES = (
    "mems_microphone",
    "small_loudspeaker",
)
_BUNDLED_SCENARIO_NAMES = (
    "conference_call",
    "drone_arrival",
    "drone_hover",
    "quiet_office",
)


def _fail(msg: str, *, where: str = "") -> None:
    prefix = f"{where}: " if where else ""
    raise ValueError(f"{prefix}{msg}")


def _as_float_list(data: Any, *, where: str = "") -> list[float]:
    if not isinstance(data, list) or not data:
        _fail(f"expected a non-empty list of numbers, got {type(data).__name__}", where=where)
    out: list[float] = []
    for i, v in enumerate(data):
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            _fail(f"element {i} is {type(v).__name__}, expected a number", where=f"{where}[{i}]")
        f = float(v)
        if not math.isfinite(f):
            _fail(f"element {i} is not finite", where=f"{where}[{i}]")
        out.append(f)
    return out


def _as_dims3(data: Any, *, where: str = "") -> tuple[float, float, float]:
    if not isinstance(data, (list, tuple)) or len(data) != 3:
        _fail(f"must be a 3-element list of numbers, got {type(data).__name__}", where=where)
    vals = _as_float_list(list(data), where=where)
    if any(v <= 0.0 for v in vals):
        _fail(f"must be strictly positive, got {vals}", where=where)
    return (float(vals[0]), float(vals[1]), float(vals[2]))


def _as_face_absorption(data: Any, *, where: str = "") -> dict[str, list[float]]:
    if not isinstance(data, dict):
        _fail(f"expected a mapping, got {type(data).__name__}", where=where)
    out: dict[str, list[float]] = {}
    for face in _REQUIRED_FACES:
        if face not in data:
            _fail(f"missing face {face!r}", where=where)
        out[face] = _as_float_list(data[face], where=f"{where}.{face}")
    for face, vals in out.items():
        for i, a in enumerate(vals):
            if not 0.0 <= a <= 1.0:
                _fail(
                    f"absorption coefficient {a} for face {face} index {i} outside [0, 1]",
                    where=f"{where}.{face}[{i}]",
                )
    return out


@dataclass(frozen=True)
class RoomPreset:
    """A validated room preset (one entry in ``configs/rooms/``).

    ``dimensions_m`` is in the ``[x, y, z]`` order expected by the
    pyroomacoustics Shoebox constructor; ``absorption`` maps each face to a
    per-frequency Sabine absorption coefficient aligned with
    ``frequencies_hz``.
    """

    name: str
    dimensions_m: tuple[float, float, float]
    frequencies_hz: tuple[float, ...]
    absorption: dict[str, tuple[float, ...]]

    def to_dict(self) -> dict[str, Any]:
        """Round-trip to the same shape as ``configs/rooms/*.yaml``.

        ``from_dict`` accepts exactly this layout (absorption block nested
        under ``absorption``), so ``RoomPreset.from_dict(p.to_dict()) == p``.
        """
        return {
            "name": self.name,
            "dimensions_m": list(self.dimensions_m),
            "absorption": {
                "frequencies_hz": list(self.frequencies_hz),
                "absorption": {face: list(vals) for face, vals in self.absorption.items()},
            },
        }

    @classmethod
    def from_dict(cls, data: Any, *, where: str = "") -> RoomPreset:
        if not isinstance(data, dict):
            _fail(f"expected a mapping, got {type(data).__name__}", where=where)

        name = data.get("name")
        if not isinstance(name, str) or not name:
            _fail("missing or invalid 'name' field", where=where)

        dims = _as_dims3(data.get("dimensions_m"), where=f"{where}.dimensions_m")

        abs_block = data.get("absorption")
        if not isinstance(abs_block, dict):
            _fail("missing 'absorption' block", where=where)
        freqs = _as_float_list(
            abs_block.get("frequencies_hz"), where=f"{where}.absorption.frequencies_hz"
        )
        if any(f <= 0.0 for f in freqs):
            _fail(f"'frequencies_hz' must be strictly positive, got {freqs}", where=where)

        faces = _as_face_absorption(
            abs_block.get("absorption"), where=f"{where}.absorption.absorption"
        )
        for face, vals in faces.items():
            if len(vals) != len(freqs):
                _fail(
                    f"face {face}: {len(vals)} absorption values vs {len(freqs)} frequencies",
                    where=f"{where}.absorption.absorption.{face}",
                )

        return cls(
            name=name,
            dimensions_m=dims,
            frequencies_hz=tuple(freqs),
            absorption={face: tuple(vals) for face, vals in faces.items()},
        )


@dataclass(frozen=True)
class DevicePreset:
    """A validated device preset (one entry in ``configs/devices/``).

    ``frequency_response_db`` is the transducer's SPL response (dB, relative
    to 0 dB) aligned element-wise with ``frequency_response_hz``; it is not
    flat because both loudspeakers and MEMS microphones roll off at the band
    edges (PLAN §2.1). ``usable_band_hz`` is the device-limited sub-band the
    band-selector should restrict itself to; ``max_spl_db`` marks the SPL
    above which the transducer compresses / clips.
    """

    name: str
    kind: str
    frequency_response_hz: tuple[float, ...]
    frequency_response_db: tuple[float, ...]
    usable_band_hz: tuple[float, float]
    max_spl_db: float

    def to_dict(self) -> dict[str, Any]:
        """Round-trip to the same shape as ``configs/devices/*.yaml``."""
        return {
            "name": self.name,
            "kind": self.kind,
            "frequency_response_hz": list(self.frequency_response_hz),
            "frequency_response_db": list(self.frequency_response_db),
            "usable_band_hz": list(self.usable_band_hz),
            "max_spl_db": self.max_spl_db,
        }

    @classmethod
    def from_dict(cls, data: Any, *, where: str = "") -> DevicePreset:
        if not isinstance(data, dict):
            _fail(f"expected a mapping, got {type(data).__name__}", where=where)
        name = data.get("name")
        if not isinstance(name, str) or not name:
            _fail("missing or invalid 'name' field", where=where)
        kind = data.get("kind")
        if kind not in _DEVICE_KINDS:
            _fail(f"kind must be one of {list(_DEVICE_KINDS)}, got {kind!r}", where=f"{where}.kind")
        freqs = _as_float_list(
            data.get("frequency_response_hz"), where=f"{where}.frequency_response_hz"
        )
        if any(f <= 0.0 for f in freqs):
            _fail(
                "frequency_response_hz must be strictly positive",
                where=f"{where}.frequency_response_hz",
            )
        if len(freqs) >= 2 and any(b <= a for a, b in zip(freqs, freqs[1:], strict=False)):
            _fail(
                "frequency_response_hz must be strictly increasing",
                where=f"{where}.frequency_response_hz",
            )
        resp = _as_float_list(
            data.get("frequency_response_db"), where=f"{where}.frequency_response_db"
        )
        if len(resp) != len(freqs):
            _fail(
                f"frequency_response_db ({len(resp)}) must align with "
                f"frequency_response_hz ({len(freqs)})",
                where=f"{where}.frequency_response_db",
            )
        band = _as_float_list(data.get("usable_band_hz"), where=f"{where}.usable_band_hz")
        if len(band) != 2:
            _fail("usable_band_hz must have exactly 2 entries", where=f"{where}.usable_band_hz")
        if band[0] >= band[1]:
            _fail(
                "usable_band_hz low bound must be < high bound",
                where=f"{where}.usable_band_hz",
            )
        max_spl = data.get("max_spl_db")
        if (
            isinstance(max_spl, bool)
            or not isinstance(max_spl, (int, float))
            or not math.isfinite(float(max_spl))
            or max_spl <= 0.0
        ):
            _fail("max_spl_db must be a positive finite number", where=f"{where}.max_spl_db")
        return cls(
            name=name,
            kind=kind,
            frequency_response_hz=tuple(freqs),
            frequency_response_db=tuple(resp),
            usable_band_hz=(float(band[0]), float(band[1])),
            max_spl_db=float(max_spl),
        )


@dataclass(frozen=True)
class NoiseSource:
    """A validated noise source in a scenario (PLAN §2.5).

    ``level_db_spl`` is the source level at ``distance_m``; ``center_hz`` is
    the characteristic frequency (e.g. blade-passing for a rotor) and may be
    ``None`` for broadband sources.
    """

    kind: str
    level_db_spl: float
    distance_m: float
    center_hz: float | None = None

    def to_dict(self) -> dict[str, Any]:
        """Round-trip to the same shape as a ``noise_sources`` list entry."""
        out: dict[str, Any] = {
            "kind": self.kind,
            "level_db_spl": self.level_db_spl,
            "distance_m": self.distance_m,
        }
        if self.center_hz is not None:
            out["center_hz"] = self.center_hz
        return out

    @classmethod
    def from_dict(cls, data: Any, *, where: str = "") -> NoiseSource:
        if not isinstance(data, dict):
            _fail(f"expected a mapping, got {type(data).__name__}", where=where)
        kind = data.get("kind")
        if not isinstance(kind, str) or not kind:
            _fail("missing or invalid 'kind' field", where=f"{where}.kind")
        level = data.get("level_db_spl")
        if (
            isinstance(level, bool)
            or not isinstance(level, (int, float))
            or not math.isfinite(float(level))
            or level <= 0.0
        ):
            _fail("level_db_spl must be a positive finite number", where=f"{where}.level_db_spl")
        distance = data.get("distance_m")
        if (
            isinstance(distance, bool)
            or not isinstance(distance, (int, float))
            or not math.isfinite(float(distance))
            or distance <= 0.0
        ):
            _fail("distance_m must be a positive finite number", where=f"{where}.distance_m")
        center = data.get("center_hz")
        if center is not None and (
            isinstance(center, bool)
            or not isinstance(center, (int, float))
            or not math.isfinite(float(center))
            or float(center) <= 0.0
        ):
            _fail(
                "center_hz must be a positive finite number when present",
                where=f"{where}.center_hz",
            )
        return cls(
            kind=kind,
            level_db_spl=float(level),
            distance_m=float(distance),
            center_hz=None if center is None else float(center),
        )


@dataclass(frozen=True)
class Scenario:
    """A validated scenario preset (one entry in ``configs/scenarios/``).

    ``tx_device`` / ``rx_device`` are references to device-preset names and
    ``room`` is a logical room reference (not necessarily a ``configs/rooms``
    file stem); they are validated here only as non-empty strings, and
    resolved by the caller. ``drone_speed_ms`` is the drone's translational
    speed (0.0 = stationary / hover), and ``seed`` is the RNG seed for
    deterministic simulation runs (PLAN §5).
    """

    name: str
    room: str
    tx_device: str
    rx_device: str
    noise_sources: tuple[NoiseSource, ...]
    drone_speed_ms: float
    frame_mode: str
    seed: int

    def to_dict(self) -> dict[str, Any]:
        """Round-trip to the same shape as ``configs/scenarios/*.yaml``."""
        return {
            "name": self.name,
            "room": self.room,
            "tx_device": self.tx_device,
            "rx_device": self.rx_device,
            "noise_sources": [ns.to_dict() for ns in self.noise_sources],
            "drone_speed_ms": self.drone_speed_ms,
            "frame_mode": self.frame_mode,
            "seed": self.seed,
        }

    @classmethod
    def from_dict(cls, data: Any, *, where: str = "") -> Scenario:
        if not isinstance(data, dict):
            _fail(f"expected a mapping, got {type(data).__name__}", where=where)

        name = data.get("name")
        if not isinstance(name, str) or not name:
            _fail("missing or invalid 'name' field", where=where)

        room = data.get("room")
        if not isinstance(room, str) or not room:
            _fail("missing or invalid 'room' field", where=f"{where}.room")

        tx_device = data.get("tx_device")
        if not isinstance(tx_device, str) or not tx_device:
            _fail("missing or invalid 'tx_device' field", where=f"{where}.tx_device")

        rx_device = data.get("rx_device")
        if not isinstance(rx_device, str) or not rx_device:
            _fail("missing or invalid 'rx_device' field", where=f"{where}.rx_device")

        raw_sources = data.get("noise_sources")
        if raw_sources is None:
            noise_sources: tuple[NoiseSource, ...] = ()
        elif isinstance(raw_sources, (list, tuple)):
            noise_sources = tuple(
                NoiseSource.from_dict(src, where=f"{where}.noise_sources[{i}]")
                for i, src in enumerate(raw_sources)
            )
        else:
            _fail(
                f"noise_sources must be a list, got {type(raw_sources).__name__}",
                where=f"{where}.noise_sources",
            )

        speed = data.get("drone_speed_ms")
        if (
            isinstance(speed, bool)
            or not isinstance(speed, (int, float))
            or not math.isfinite(float(speed))
            or float(speed) < 0.0
        ):
            _fail(
                "drone_speed_ms must be a non-negative finite number",
                where=f"{where}.drone_speed_ms",
            )

        frame_mode = data.get("frame_mode")
        if frame_mode not in _FRAME_MODES:
            _fail(
                f"frame_mode must be one of {list(_FRAME_MODES)}, got {frame_mode!r}",
                where=f"{where}.frame_mode",
            )

        seed = data.get("seed")
        if isinstance(seed, bool) or not isinstance(seed, int) or seed < 0:
            _fail("seed must be a non-negative integer", where=f"{where}.seed")

        return cls(
            name=name,
            room=room,
            tx_device=tx_device,
            rx_device=rx_device,
            noise_sources=noise_sources,
            drone_speed_ms=float(speed),
            frame_mode=frame_mode,
            seed=int(seed),
        )


def _configs_dir(presets_dir: str | Path | None = None) -> Path:
    if presets_dir is None:
        return CONFIGS_DIR
    return Path(presets_dir)


def _preset_dir(presets_dir: str | Path | None, subdir: str) -> Path:
    """Resolve the directory holding one category of presets.

    ``presets_dir`` may be either the *base* configs root (which then contains
    a ``<subdir>/`` of presets, e.g. ``configs/rooms/``) **or** the preset leaf
    directory itself. Both conventions are accepted so callers and tests can
    point straight at a folder of ``*.yaml`` files. With no override the
    bundled ``configs/`` tree is used.
    """
    if presets_dir is None:
        return CONFIGS_DIR / subdir
    base = Path(presets_dir)
    nested = base / subdir
    return nested if nested.is_dir() else base


def load_defaults(presets_dir: str | Path | None = None) -> dict[str, Any]:
    """Load ``defaults.yaml`` (seed, sample_rate_hz, audio bands).

    Returns a plain dict; callers should pull the keys they need.
    """
    path = _configs_dir(presets_dir) / "defaults.yaml"
    if not path.exists():
        raise FileNotFoundError(f"defaults.yaml not found at {path}")
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        _fail(f"defaults.yaml must be a mapping, got {type(data).__name__}", where=str(path))
    return cast("dict[str, Any]", data)


def list_room_presets(presets_dir: str | Path | None = None) -> list[str]:
    """Sorted names of every ``configs/rooms/*.yaml`` preset."""
    rooms = _preset_dir(presets_dir, ROOMS_SUBDIR)
    if not rooms.is_dir():
        return []
    return sorted(p.stem for p in rooms.glob("*.yaml") if p.is_file())


def load_room_preset(name: str, presets_dir: str | Path | None = None) -> RoomPreset:
    """Load and validate ``configs/rooms/<name>.yaml``."""
    path = _preset_dir(presets_dir, ROOMS_SUBDIR) / f"{name}.yaml"
    if not path.exists():
        available = ", ".join(list_room_presets(presets_dir)) or "(none)"
        raise FileNotFoundError(f"room preset {name!r} not found at {path}; available: {available}")
    data = yaml.safe_load(path.read_text())
    return RoomPreset.from_dict(data, where=str(path))


def all_room_presets(presets_dir: str | Path | None = None) -> list[RoomPreset]:
    """Load every bundled preset, in a stable (sorted-by-name) order."""
    return [load_room_preset(n, presets_dir) for n in list_room_presets(presets_dir)]


def list_devices(presets_dir: str | Path | None = None) -> list[str]:
    """Sorted names of every ``configs/devices/*.yaml`` preset."""
    devices = _preset_dir(presets_dir, DEVICES_SUBDIR)
    if not devices.is_dir():
        return []
    return sorted(p.stem for p in devices.glob("*.yaml") if p.is_file())


def load_device_preset(name: str, presets_dir: str | Path | None = None) -> DevicePreset:
    """Load and validate ``configs/devices/<name>.yaml``."""
    path = _preset_dir(presets_dir, DEVICES_SUBDIR) / f"{name}.yaml"
    if not path.exists():
        available = ", ".join(list_devices(presets_dir)) or "(none)"
        raise FileNotFoundError(
            f"device preset {name!r} not found at {path}; available: {available}"
        )
    data = yaml.safe_load(path.read_text())
    return DevicePreset.from_dict(data, where=str(path))


def list_scenarios(presets_dir: str | Path | None = None) -> list[str]:
    """Sorted names of every ``configs/scenarios/*.yaml`` scenario."""
    scenarios = _preset_dir(presets_dir, SCENARIOS_SUBDIR)
    if not scenarios.is_dir():
        return []
    return sorted(p.stem for p in scenarios.glob("*.yaml") if p.is_file())


def load_scenario(name: str, presets_dir: str | Path | None = None) -> Scenario:
    """Load and validate ``configs/scenarios/<name>.yaml``."""
    path = _preset_dir(presets_dir, SCENARIOS_SUBDIR) / f"{name}.yaml"
    if not path.exists():
        available = ", ".join(list_scenarios(presets_dir)) or "(none)"
        raise FileNotFoundError(f"scenario {name!r} not found at {path}; available: {available}")
    data = yaml.safe_load(path.read_text())
    return Scenario.from_dict(data, where=str(path))


def all_scenarios(presets_dir: str | Path | None = None) -> list[Scenario]:
    """Load every scenario, in a stable (sorted-by-name) order."""
    return [load_scenario(n, presets_dir) for n in list_scenarios(presets_dir)]


def validate_scenario_references(presets_dir: str | Path | None = None) -> list[str]:
    """Check every scenario's ``room`` / device references resolve.

    ``Scenario.from_dict`` validates the *shape* of a scenario but deliberately
    does not resolve its string references (a scenario is a logical preset and
    its room reference is not necessarily a ``configs/rooms`` file stem). This
    helper closes that gap for a bundled tree: for each scenario it reports a
    problem when ``room`` / ``tx_device`` / ``rx_device`` does not name an
    existing room or device preset. Returns a list of human-readable problems
    (empty = all references resolve).

    A category directory that does not exist at all is not treated as an error
    (e.g. a stripped checkout with only scenarios); only *missing names* are
    reported.
    """
    problems: list[str] = []
    room_names = set(list_room_presets(presets_dir))
    device_names = set(list_devices(presets_dir))
    for s in all_scenarios(presets_dir):
        if room_names and s.room not in room_names:
            problems.append(
                f"scenario {s.name!r}: room {s.room!r} not found "
                f"(available: {', '.join(sorted(room_names)) or '(none)'})"
            )
        if device_names and s.tx_device not in device_names:
            problems.append(
                f"scenario {s.name!r}: tx_device {s.tx_device!r} not found "
                f"(available: {', '.join(sorted(device_names)) or '(none)'})"
            )
        if device_names and s.rx_device not in device_names:
            problems.append(
                f"scenario {s.name!r}: rx_device {s.rx_device!r} not found "
                f"(available: {', '.join(sorted(device_names)) or '(none)'})"
            )
    return problems


# --- C2 frontier sweep (S17.2) ---------------------------------------------


#: Allowed ``aggregator`` strategies for the C2 frontier sweep.
_ALLOWED_AGGREGATORS = ("best", "mean", "consensus")

#: Allowed perceptual signal types (kept in sync with
#: ``metrics.perceptual._SIGNAL_TYPES``).  The first three use the reference-ramp
#: annoyance model; ``css``/``mfsk`` use the frequency-dependent modulation
#: factors.
_ALLOWED_PERCEPTUAL_SIGNAL_TYPES = ("noise", "sharp", "rough", "css", "mfsk")
#: Allowed ``noise_kind`` references for the ``"noise"`` signal type.
_ALLOWED_NOISE_KINDS = ("broadband", "pink")


def _as_positive_float_list(data: Any, *, where: str = "") -> list[float]:
    vals = _as_float_list(data, where=where)
    if any(v <= 0.0 for v in vals):
        _fail(f"must be strictly positive, got {vals}", where=where)
    return vals


def _as_pos_num(data: Any, *, where: str = "") -> float:
    if isinstance(data, bool) or not isinstance(data, (int, float)):
        _fail(f"expected a number, got {type(data).__name__}", where=where)
    f = float(data)
    if not math.isfinite(f):
        _fail(f"{f!r} is not finite", where=where)
    if f <= 0.0:
        _fail(f"must be strictly positive, got {f!r}", where=where)
    return f


def _as_finite_num(data: Any, *, where: str = "") -> float:
    if isinstance(data, bool) or not isinstance(data, (int, float)):
        _fail(f"expected a number, got {type(data).__name__}", where=where)
    f = float(data)
    if not math.isfinite(f):
        _fail(f"{f!r} is not finite", where=where)
    return f


def _as_bands(data: Any, *, where: str = "") -> list[tuple[float, float]]:
    if not isinstance(data, list) or not data:
        _fail(
            f"expected a non-empty list of [lo_hz, hi_hz] pairs, got {type(data).__name__}",
            where=where,
        )
    out: list[tuple[float, float]] = []
    for i, band in enumerate(data):
        where_i = f"{where}[{i}]"
        if not isinstance(band, (list, tuple)) or len(band) != 2:
            _fail(
                f"each candidate must be a 2-element [lo_hz, hi_hz] pair, got {band!r}",
                where=where_i,
            )
        lo = _as_pos_num(band[0], where=f"{where_i}[0]")
        hi = _as_pos_num(band[1], where=f"{where_i}[1]")
        if lo >= hi:
            _fail(f"low frequency {lo!r} must be < high frequency {hi!r}", where=where_i)
        out.append((lo, hi))
    return out


@dataclass(frozen=True)
class FrontierConfig:
    """A validated C2 frontier-sweep configuration (``configs/c2_frontier.yaml``).

    The sweep grids over ``band_candidates`` (each a ``[lo_hz, hi_hz]`` pair),
    an ``spl_db`` working point, a ``snr_db`` axis, a ``bler_max`` budget, a
    ``ttch_max_s`` latency budget, a ``symbols_per_second`` target, and an
    ``n_chirps`` / ``lambda_grid`` chirp axis. ``aggregator`` selects how the
    per-point frontier is combined and ``room`` names the room to sweep in.
    """

    band_candidates: tuple[tuple[float, float], ...]
    spl_db: float
    snr_db: float
    bler_max: float
    ttch_max_s: float
    symbols_per_second: float
    n_chirps: int
    lambda_grid: tuple[float, ...]
    aggregator: str
    room: str
    #: When true, sim-10 scores the C2 frontier with the perceptual *annoyance*
    #: measure (``metrics.rate.make_perceptual_cost_fn``) instead of the
    #: parametric dB audibility cost (PLAN §2.6 / §9.4).  Defaults to False so
    #: the legacy dB path is unchanged unless the YAML opts in.
    use_perceptual_cost: bool = False
    #: Perceptual signal type driving the annoyance penalty (see
    #: ``metrics.perceptual.perceptual_annoyance``): ``"noise"``, ``"sharp"``,
    #: ``"rough"`` (reference-ramp models) or ``"css"`` / ``"mfsk"``
    #: (frequency-dependent modulation factors).  Only read when
    #: ``use_perceptual_cost`` is true; defaults to ``"noise"``.
    perceptual_signal_type: str = "noise"
    #: Noise kind used for the ``"noise"`` signal type's loudness reference
    #: (``"broadband"`` / ``"pink"``); ignored for the other signal types.
    #: Defaults to ``"broadband"``.
    perceptual_noise_kind: str = "broadband"

    def to_dict(self) -> dict[str, Any]:
        """Round-trip to the same shape as ``configs/c2_frontier.yaml``."""
        return {
            "band_candidates": [[lo, hi] for lo, hi in self.band_candidates],
            "spl_db": self.spl_db,
            "snr_db": self.snr_db,
            "bler_max": self.bler_max,
            "ttch_max_s": self.ttch_max_s,
            "symbols_per_second": self.symbols_per_second,
            "n_chirps": self.n_chirps,
            "lambda_grid": list(self.lambda_grid),
            "aggregator": self.aggregator,
            "room": self.room,
            "use_perceptual_cost": self.use_perceptual_cost,
            "perceptual_signal_type": self.perceptual_signal_type,
            "perceptual_noise_kind": self.perceptual_noise_kind,
        }

    @classmethod
    def from_dict(cls, data: Any, *, where: str = "") -> FrontierConfig:
        if not isinstance(data, dict):
            _fail(f"expected a mapping, got {type(data).__name__}", where=where)

        bands = _as_bands(data.get("band_candidates"), where=f"{where}.band_candidates")
        spl_db = _as_pos_num(data.get("spl_db"), where=f"{where}.spl_db")
        snr_db = _as_finite_num(data.get("snr_db"), where=f"{where}.snr_db")

        bler_raw = data.get("bler_max")
        if isinstance(bler_raw, bool) or not isinstance(bler_raw, (int, float)):
            _fail(f"expected a number, got {type(bler_raw).__name__}", where=f"{where}.bler_max")
        bler_max = float(bler_raw)
        if not math.isfinite(bler_max) or not (0.0 < bler_max <= 1.0):
            _fail(f"must be in (0, 1], got {bler_max!r}", where=f"{where}.bler_max")

        ttch_max_s = _as_pos_num(data.get("ttch_max_s"), where=f"{where}.ttch_max_s")
        symbols_per_second = _as_pos_num(
            data.get("symbols_per_second"), where=f"{where}.symbols_per_second"
        )

        n_chirps_raw = data.get("n_chirps")
        if isinstance(n_chirps_raw, bool) or not isinstance(n_chirps_raw, int):
            _fail(f"expected an int, got {type(n_chirps_raw).__name__}", where=f"{where}.n_chirps")
        if n_chirps_raw <= 0:
            _fail(f"must be strictly positive, got {n_chirps_raw!r}", where=f"{where}.n_chirps")

        lambda_grid = _as_positive_float_list(data.get("lambda_grid"), where=f"{where}.lambda_grid")

        aggregator = data.get("aggregator")
        if not isinstance(aggregator, str) or not aggregator:
            _fail("missing or invalid 'aggregator' field", where=where)
        if aggregator not in _ALLOWED_AGGREGATORS:
            _fail(
                f"invalid aggregator {aggregator!r}; "
                f"allowed: {', '.join(_ALLOWED_AGGREGATORS)}",
                where=where,
            )

        room = data.get("room")
        if not isinstance(room, str) or not room:
            _fail("missing or invalid 'room' field", where=where)

        use_perceptual_cost = data.get("use_perceptual_cost", False)
        if not isinstance(use_perceptual_cost, bool):
            _fail(
                f"expected a bool, got {type(use_perceptual_cost).__name__}",
                where=f"{where}.use_perceptual_cost",
            )

        perceptual_signal_type = data.get("perceptual_signal_type", "noise")
        if not isinstance(perceptual_signal_type, str) or not perceptual_signal_type:
            _fail(
                "missing or invalid 'perceptual_signal_type' field (expected a string)",
                where=f"{where}.perceptual_signal_type",
            )
        if perceptual_signal_type not in _ALLOWED_PERCEPTUAL_SIGNAL_TYPES:
            _fail(
                f"invalid perceptual_signal_type {perceptual_signal_type!r}; "
                f"allowed: {', '.join(_ALLOWED_PERCEPTUAL_SIGNAL_TYPES)}",
                where=f"{where}.perceptual_signal_type",
            )

        perceptual_noise_kind = data.get("perceptual_noise_kind", "broadband")
        if not isinstance(perceptual_noise_kind, str) or not perceptual_noise_kind:
            _fail(
                "missing or invalid 'perceptual_noise_kind' field (expected a string)",
                where=f"{where}.perceptual_noise_kind",
            )
        if perceptual_noise_kind not in _ALLOWED_NOISE_KINDS:
            _fail(
                f"invalid perceptual_noise_kind {perceptual_noise_kind!r}; "
                f"allowed: {', '.join(_ALLOWED_NOISE_KINDS)}",
                where=f"{where}.perceptual_noise_kind",
            )

        return cls(
            band_candidates=tuple(bands),
            spl_db=spl_db,
            snr_db=snr_db,
            bler_max=bler_max,
            ttch_max_s=ttch_max_s,
            symbols_per_second=symbols_per_second,
            n_chirps=n_chirps_raw,
            lambda_grid=tuple(lambda_grid),
            aggregator=aggregator,
            room=room,
            use_perceptual_cost=use_perceptual_cost,
            perceptual_signal_type=perceptual_signal_type,
            perceptual_noise_kind=perceptual_noise_kind,
        )


#: Canonical file name of the C2 frontier-sweep config (repo-root-relative).
FRONTIER_FILENAME = "c2_frontier.yaml"


def load_frontier(presets_dir: str | Path | None = None) -> FrontierConfig:
    """Load and validate ``configs/c2_frontier.yaml`` (S17.2).

    Mirrors :func:`load_room_preset`: the file is read here and *only* here,
    and validated into a frozen :class:`FrontierConfig` so a typo in the YAML
    (unknown key, out-of-range value, ``lo >= hi`` band) fails loudly at load
    time rather than mid-sweep.
    """
    base = Path(presets_dir) if presets_dir is not None else CONFIGS_DIR
    path = base / FRONTIER_FILENAME
    if not path.exists():
        raise FileNotFoundError(f"c2 frontier config not found at {path}")
    data = yaml.safe_load(path.read_text())
    return FrontierConfig.from_dict(data, where=str(path))


